from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path
from typing import Any


def normalise_identifier(value: str) -> str:
    """Return a lowercase identifier suitable for comparison."""
    return value.strip().lower()


def record_key(row: dict[str, str]) -> str:
    """Prefer DOI, then OpenAlex ID, then title as a deduplication key."""
    doi = normalise_identifier(row.get("doi", ""))

    if doi:
        return f"doi:{doi}"

    openalex_id = normalise_identifier(row.get("openalex_id", ""))

    if openalex_id:
        return f"openalex:{openalex_id}"

    title = normalise_identifier(row.get("title", ""))

    if title:
        return f"title:{title}"

    raise ValueError("Record has no DOI, OpenAlex ID, or title")


def read_csv(path: Path) -> list[dict[str, str]]:
    """Read OpenAlex query results from CSV."""
    with path.open(encoding="utf-8", newline="") as file:
        return list(csv.DictReader(file))


def deduplicate_rows(rows: list[dict[str, str]]) -> list[dict[str, Any]]:
    """Merge duplicate records while retaining query provenance."""
    grouped: dict[str, list[dict[str, str]]] = defaultdict(list)

    for row in rows:
        grouped[record_key(row)].append(row)

    deduplicated = []

    for matching_rows in grouped.values():
        matching_rows.sort(
            key=lambda row: (
                row.get("query_id", ""),
                int(row.get("rank", "0") or 0),
            )
        )

        first = matching_rows[0]

        query_ids = sorted(
            {
                row.get("query_id", "")
                for row in matching_rows
                if row.get("query_id")
            }
        )

        categories = sorted(
            {
                row.get("category", "")
                for row in matching_rows
                if row.get("category")
            }
        )

        best_rank = min(
            int(row.get("rank", "0") or 0)
            for row in matching_rows
        )

        deduplicated.append(
            {
                "openalex_id": first.get("openalex_id", ""),
                "doi": first.get("doi", ""),
                "title": first.get("title", ""),
                "publication_year": first.get("publication_year", ""),
                "type": first.get("type", ""),
                "source": first.get("source", ""),
                "authors": first.get("authors", ""),
                "cited_by_count": first.get("cited_by_count", ""),
                "query_count": len(query_ids),
                "query_ids": ";".join(query_ids),
                "categories": ";".join(categories),
                "best_rank": best_rank,
            }
        )

    deduplicated.sort(
        key=lambda row: (
            -int(row["query_count"]),
            int(row["best_rank"]),
            str(row["title"]).lower(),
        )
    )

    return deduplicated


def write_csv(rows: list[dict[str, Any]], path: Path) -> None:
    """Write deduplicated results to CSV."""
    path.parent.mkdir(parents=True, exist_ok=True)

    fieldnames = [
        "openalex_id",
        "doi",
        "title",
        "publication_year",
        "type",
        "source",
        "authors",
        "cited_by_count",
        "query_count",
        "query_ids",
        "categories",
        "best_rank",
    ]

    with path.open("w", encoding="utf-8", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Deduplicate OpenAlex query results."
    )
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("data/raw/openalex_query_results.csv"),
        help="Input CSV generated by run_openalex_queries.py.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("data/processed/openalex_deduplicated.csv"),
        help="Output CSV for deduplicated records.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    rows = read_csv(args.input)
    deduplicated = deduplicate_rows(rows)
    write_csv(deduplicated, args.output)

    duplicate_count = len(rows) - len(deduplicated)

    print(f"Input records: {len(rows)}")
    print(f"Unique records: {len(deduplicated)}")
    print(f"Duplicate query hits merged: {duplicate_count}")
    print(f"Saved to: {args.output}")


if __name__ == "__main__":
    main()
